export function renderIvrPromptMessage(
  locale: IvrPromptLocale,
  key: IvrPromptMessageKey,
  values: Readonly<Record<string, string>> = {},
): string {
  const template = ivrPromptCatalogs[locale][key] ?? ivrPromptCatalogs.en[key];
  return template.replace(/\{([A-Za-z][\w.]*)\}/gu, (placeholder, name: string) => values[name] ?? placeholder);
}
